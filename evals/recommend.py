#!/usr/bin/env python
"""AgentCore Optimization, step 1 of the iteration in data doc section 4.5.3: ask for a system-prompt recommendation
against the rationale rubric, from the traces of a finished dataset run.

    uv run evals/recommend.py start evals/runs/<run_id>          # traces = that run's time window on the Runtime log group
    uv run evals/recommend.py get <recommendation_id>            # poll; writes evals/recommendations/<id>.{json,md} when done
    uv run evals/recommend.py list

The current prompt is the text the agent really runs with (`prompt.system_prompt("investigate")`), passed inline.
The target evaluator is the custom rubric (single numerical scale, no ground truth: the two conditions the service
puts on recommendation evaluators [devguide "Start a system prompt recommendation", read 2026-11-06]). The
recommendation itself is free; the Evaluations it consumes are billed.

The result is a candidate, not a change: it becomes bundle v2 only if it passes the offline promotion rule
(data doc 4.4) on a full run, which is where the gate lives. Recommendations are generated by a model; read the
`explanation` before trusting the text.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path

import boto3

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app" / "surv_investigator_l1"))
sys.path.insert(0, str(ROOT / "evals"))

REGION = "eu-west-2"
ACCOUNT = boto3.client("sts", region_name=REGION).get_caller_identity()["Account"]
RUNTIME_ID = "surv_default_surv_investigator_l1-lrnjCN5vBp"
LOG_GROUP = f"/aws/bedrock-agentcore/runtimes/{RUNTIME_ID}-DEFAULT"
LOG_GROUP_ARN = f"arn:aws:logs:{REGION}:{ACCOUNT}:log-group:{LOG_GROUP}"
SERVICE_NAME = "surv_default_surv_investigator_l1.DEFAULT"
OUT_DIR = ROOT / "evals" / "recommendations"
TAGS = {"Project": "agentcore-surveillance-investigator", "auto-delete": "no"}


def dp():
    return boto3.client("bedrock-agentcore", region_name=REGION)


def rubric_arn() -> str:
    from evaluate_sessions import rubric_id

    return f"arn:aws:bedrock-agentcore:{REGION}:{ACCOUNT}:evaluator/{rubric_id()}"


def current_prompt() -> str:
    from prompt import system_prompt

    return system_prompt("investigate")


def start(run_dir: Path, evaluator_arn: str, name: str | None) -> dict:
    run = json.loads((run_dir / "results.json").read_text())
    t0 = datetime.fromisoformat(run["started_at"]) - timedelta(minutes=2)
    t1 = datetime.fromisoformat(run["finished_at"]) + timedelta(minutes=10)
    text = current_prompt()
    if len(text) > 20000:
        raise SystemExit(f"system prompt is {len(text)} chars; the API accepts 20,000")
    name = name or re.sub(r"[^a-zA-Z0-9_-]", "-", f"surv-{run['run_id']}")[:48]
    if not re.match(r"[a-zA-Z]", name[0]):
        name = "r" + name[1:]
    # the recommendation runs the rubric judge (Opus) over every session in the window and then an optimiser on top:
    # the one judged pass cost about $12 in judge tokens for 167 sessions. Nothing here runs without a yes.
    n = run["metrics"]["n"]
    print(
        f"this starts a judged pass over {n} sessions (rubric on Opus, ~$0.07 each, about ${0.07 * n:.0f}) plus the optimiser"
    )
    if input("start the recommendation? [y/N] ").strip().lower() not in ("y", "yes"):
        raise SystemExit("not started")
    r = dp().start_recommendation(
        name=name,
        description=f"System-prompt recommendation against {evaluator_arn.rsplit('/', 1)[1]} from run {run['run_id']} "
        f"({run['n_selected']} sessions, {run['metrics']['n']} alerts).",
        type="SYSTEM_PROMPT_RECOMMENDATION",
        recommendationConfig={
            "systemPromptRecommendationConfig": {
                "systemPrompt": {"text": text},
                "agentTraces": {
                    "cloudwatchLogs": {
                        "logGroupArns": [LOG_GROUP_ARN],
                        "serviceNames": [SERVICE_NAME],
                        "startTime": t0.astimezone(UTC),
                        "endTime": t1.astimezone(UTC),
                    }
                },
                "evaluationConfig": {"evaluators": [{"evaluatorArn": evaluator_arn}]},
            }
        },
        clientToken=str(uuid.uuid4()),
        tags=TAGS,
    )
    OUT_DIR.mkdir(exist_ok=True)
    meta = {
        "recommendation_id": r["recommendationId"],
        "recommendation_arn": r["recommendationArn"],
        "name": name,
        "status": r["status"],
        "run_id": run["run_id"],
        "evaluator_arn": evaluator_arn,
        "trace_window": [t0.isoformat(), t1.isoformat()],
        "input_prompt_chars": len(text),
        "started_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    (OUT_DIR / f"{r['recommendationId']}.json").write_text(json.dumps(meta, indent=1))
    (OUT_DIR / f"{r['recommendationId']}.input-prompt.txt").write_text(text)
    print(json.dumps(meta, indent=1))
    return meta


def get(rec_id: str, wait: bool) -> dict:
    c = dp()
    while True:
        r = c.get_recommendation(recommendationId=rec_id)
        status = r.get("status")
        print(f"{datetime.now(UTC).strftime('%H:%M:%S')} {rec_id} {status}", flush=True)
        if status in ("COMPLETED", "FAILED", "DELETING") or not wait:
            break
        time.sleep(60)
    OUT_DIR.mkdir(exist_ok=True)
    path = OUT_DIR / f"{rec_id}.json"
    meta = json.loads(path.read_text()) if path.exists() else {"recommendation_id": rec_id}
    meta.update(status=status, fetched_at=datetime.now(UTC).isoformat(timespec="seconds"))
    res = r.get("recommendationResult") or {}
    meta["result_keys"] = list(res.keys())
    body = res.get("systemPromptRecommendationResult") or res
    if body.get("recommendedSystemPrompt"):
        (OUT_DIR / f"{rec_id}.recommended-prompt.txt").write_text(body["recommendedSystemPrompt"])
        meta["recommended_prompt_chars"] = len(body["recommendedSystemPrompt"])
    for k in ("explanation", "errorCode", "errorMessage"):
        if body.get(k):
            meta[k] = body[k]
    path.write_text(json.dumps(meta, indent=1, default=str))
    if body.get("explanation"):
        md = [
            f"# Recommendation `{rec_id}`",
            "",
            f"Status {status}; run `{meta.get('run_id')}`; evaluator `{meta.get('evaluator_arn', '').rsplit('/', 1)[-1]}`.",
            "",
            "## Explanation",
            "",
            body["explanation"],
            "",
        ]
        if body.get("recommendedSystemPrompt"):
            md += ["## Recommended system prompt", "", "```", body["recommendedSystemPrompt"], "```", ""]
        (OUT_DIR / f"{rec_id}.md").write_text("\n".join(md))
        print((OUT_DIR / f"{rec_id}.md").read_text()[:4000])
    elif body.get("errorMessage"):
        print(f"!! {body.get('errorCode')}: {body.get('errorMessage')}")
    return meta


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=["start", "get", "list"])
    ap.add_argument("target", nargs="?", help="run dir for start, recommendation id for get")
    ap.add_argument("--evaluator-arn", default=None, help="default: the project's rationale rubric")
    ap.add_argument("--name", default=None)
    ap.add_argument("--wait", action="store_true", help="with get: poll until finished")
    args = ap.parse_args()
    if args.action == "list":
        for r in dp().list_recommendations(maxResults=50).get("recommendationSummaries", []) or []:
            print(f"{r.get('recommendationId'):50s} {r.get('status'):12s} {r.get('type')}  {r.get('createdAt')}")
        return 0
    if not args.target:
        raise SystemExit("target is required")
    if args.action == "start":
        start(Path(args.target), args.evaluator_arn or rubric_arn(), args.name)
    else:
        get(args.target, args.wait)
    return 0


if __name__ == "__main__":
    sys.exit(main())
